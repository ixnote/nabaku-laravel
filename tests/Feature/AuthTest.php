<?php

namespace Tests\Feature;

use App\Models\Address;
use App\Models\Organization;
use App\Models\Outbox;
use App\Models\User;
use Firebase\JWT\JWT;
use Illuminate\Support\Facades\Crypt;
use Illuminate\Support\Facades\DB;
use MongoDB\BSON\ObjectId;
use Tests\MongoTestCase;

class AuthTest extends MongoTestCase
{
    public function test_registration_activation_login_profile_and_privilege_protection(): void
    {
        $res = $this->postJson('/api/v1/authentication/register', ['email' => 'New@Example.test', 'phone' => '08000000111', 'password' => 'password123', 'isAdmin' => true]);
        $res->assertCreated()->assertJsonPath('data.email', 'new@example.test')->assertJsonPath('data.isAdmin', false)->assertJsonMissingPath('data.password')->assertJsonMissingPath('data.activationToken');
        $org = Organization::where('email', 'new@example.test')->firstOrFail();
        $payload = json_decode(Crypt::decryptString(Outbox::first()->encrypted_payload), true);
        $this->assertStringStartsWith('http://localhost:3000/pop?token=', $payload['url']);
        parse_str(parse_url($payload['url'], PHP_URL_QUERY), $query);
        $token = $query['token'];
        $this->getJson('/api/v1/authentication/activate/'.$token)->assertOk();
        $this->getJson('/api/v1/authentication/activate/'.$token)->assertForbidden();
        $login = $this->postJson('/api/v1/authentication/login', ['id' => $org->email, 'password' => 'password123'])->assertOk()->assertJsonPath('authorization.expiresIn', 2592000);
        $headers = ['Authorization' => 'Bearer '.$login->json('authorization.token')];
        $this->getJson('/api/v1/authentication/get-profile', $headers)->assertOk()->assertJsonPath('data._id', (string) $org->getKey());
        $this->putJson('/api/v1/authentication/set-profile', ['profile_step' => 2, 'address' => ['street' => 'Main Street', 'city' => 'Lagos', 'state' => 'Lagos', 'zipCode' => '100001']], $headers)->assertOk();
        $this->putJson('/api/v1/authentication/set-profile', ['profile_step' => 3, 'address' => ['street' => 'Updated Street', 'city' => 'Lagos', 'state' => 'Lagos', 'zipCode' => '100001']], $headers)->assertOk();
        $this->assertSame(1, Address::count());
        $this->assertSame('Updated Street', Address::first()->street);
        $raw = DB::connection()->getMongoDB()->addresses->findOne();
        $this->assertInstanceOf(ObjectId::class, $raw->organization);
        $this->getJson('/api/v1/wallet/balance/admin', $headers)->assertForbidden();
    }

    public function test_legacy_bcrypt_and_node_jwt_are_compatible(): void
    {
        $fixture = json_decode(file_get_contents(base_path('tests/fixtures/node-auth.json')), true);
        $org = $this->organization(['password' => $fixture['hash']]);
        $this->postJson('/api/v1/authentication/login', ['id' => $org->email, 'password' => $fixture['password']])->assertOk();
        // A token generated by jsonwebtoken for a stable fixture ID is accepted unchanged.
        $raw = DB::connection()->getMongoDB()->organizations;
        $raw->insertOne(['_id' => new ObjectId($fixture['id']), 'email' => 'node@example.test', 'phone' => '08099999999', 'isActive' => true, 'blocked' => false, 'password' => $fixture['hash']]);
        $this->getJson('/api/v1/authentication/get-profile', ['Authorization' => 'Bearer '.$fixture['token']])->assertOk()->assertJsonPath('data._id', $fixture['id']);
    }

    public function test_manager_scope_and_parent_block_are_enforced(): void
    {
        $org = $this->organization();
        $other = $this->organization();
        $manager = User::create(['email' => 'manager@example.test', 'organization' => $org->getKey(), 'isActive' => true]);
        $this->project($org);
        $this->project($other);
        $this->getJson('/api/v1/project/all?organization='.$other->getKey(), $this->token($manager))->assertOk()->assertJsonCount(1, 'data')->assertJsonPath('data.0.organization', (string) $org->getKey());
        $this->getJson('/api/v1/wallet/'.$other->getKey(), $this->token($manager))->assertForbidden();
        $org->update(['blocked' => true]);
        $this->getJson('/api/v1/authentication/get-profile', $this->token($manager))->assertUnauthorized();
    }

    public function test_reset_token_is_single_use_and_password_fields_are_hidden(): void
    {
        $org = $this->organization();
        $this->postJson('/api/v1/authentication/password/forgot', ['id' => $org->email])->assertOk();
        $payload = json_decode(Crypt::decryptString(Outbox::first()->encrypted_payload), true);
        $this->assertStringStartsWith('http://localhost:3000/reset-password?token=', $payload['url']);
        parse_str(parse_url($payload['url'], PHP_URL_QUERY), $query);
        $this->assertSame($org->email, $query['email']);
        $token = $query['token'];
        $this->postJson('/api/v1/authentication/password/reset', ['token' => $token, 'password' => 'newpassword123'])->assertOk();
        $this->postJson('/api/v1/authentication/password/reset', ['token' => $token, 'password' => 'otherpassword123'])->assertForbidden();
        $this->postJson('/api/v1/authentication/login', ['id' => $org->email, 'password' => 'newpassword123'])->assertOk()->assertJsonMissingPath('data.resetPasswordExpires');
    }

    public function test_invalid_and_expired_tokens_fail_without_server_error(): void
    {
        $this->getJson('/api/v1/authentication/get-profile', ['Authorization' => 'Bearer malformed'])->assertUnauthorized();
        $org = $this->organization();
        $token = JWT::encode(['id' => (string) $org->getKey(), 'exp' => time() - 1], config('fundraiser.jwt_secret'), 'HS256');
        $this->getJson('/api/v1/authentication/get-profile', ['Authorization' => 'Bearer '.$token])->assertUnauthorized();
    }

    public function test_manager_cannot_withdraw_and_expired_activation_cannot_be_used(): void
    {
        $o = $this->organization();
        $m = User::create(['email' => 'manager-denied@example.test', 'organization' => $o->getKey(), 'isActive' => true]);
        $this->postJson('/api/v1/withdraw', ['amount' => 1000, 'bankId' => '507f1f77bcf86cd799439099'], $this->token($m))->assertForbidden();
        $token = str_repeat('a', 64);
        $o->update(['isActive' => false, 'activationToken' => hash('sha256', $token), 'activationExpires' => now()->subMinute()]);
        $this->getJson('/api/v1/authentication/activate/'.$token)->assertForbidden();
    }

    public function test_settings_edits_keep_kyb_progress_and_can_clear_fields(): void
    {
        $org = $this->organization(['profile_step' => 7, 'profile_image' => 'https://images.example.test/logo.jpg']);
        $headers = $this->token($org);
        $this->putJson('/api/v1/authentication/set-profile', ['organization_details' => ['name' => 'Renamed Organization', 'description' => '', 'profile_image' => ''], 'contact_details' => ['phone' => '08011112222', 'twitter' => '']], $headers)->assertOk();
        $org->refresh();
        $this->assertSame(7, $org->profile_step);
        $this->assertSame('Renamed Organization', $org->name);
        $this->assertSame('', $org->profile_image);
        $this->assertSame('', $org->description);
        $this->putJson('/api/v1/authentication/set-profile', ['organization_details' => ['name' => 'ab']], $headers)->assertStatus(400);
    }
}
